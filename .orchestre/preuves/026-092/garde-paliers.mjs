import assert from 'node:assert/strict'
import { trier, HORS } from '../../../lib/pilotage/station.ts'

const enveloppe = (valeur) => ({ valeur, source: 'supabase', a: '2026-09-30T12:00:00Z', cache: false })
const entree = enveloppe({ carte: enveloppe({ paliers: enveloppe({ envois: { lv: 2, texte: 'mesuré' }, usine: { lv: 1, texte: 'site' }, commandement: { lv: 3, texte: 'niveau lié aux recettes' } }) }) })
const avant = structuredClone(entree)
const refuse = trier(entree, (d) => d !== 'comptabilite')
assert.deepEqual(refuse.valeur.carte.valeur.paliers.valeur.commandement, HORS)
assert.deepEqual(refuse.valeur.carte.valeur.paliers.valeur.envois, entree.valeur.carte.valeur.paliers.valeur.envois)
assert.deepEqual(refuse.valeur.carte.valeur.paliers.valeur.usine, entree.valeur.carte.valeur.paliers.valeur.usine)
assert.deepEqual(trier(entree, () => true), entree)
assert.deepEqual(entree, avant)
assert.deepEqual(trier({ lv: 3 }, () => false, 'direct.carte.paliers.commandement'), HORS)
const machines = enveloppe({ ia: enveloppe({ cout_jour_eur: 1.25, fournisseurs: [{ objet: 'ia:essai', resume: 'mesure', le: '2026-09-30T12:00:00Z' }], bascules: [{ resume: 'quota', le: '2026-09-30T12:00:00Z' }] }) })
const machinesAvant = structuredClone(machines)
const machinesRefus = trier(machines, (d) => d !== 'comptabilite', 'salle.machines')
assert.deepEqual(machinesRefus.valeur.ia.valeur.cout_jour_eur, HORS)
assert.deepEqual(machinesRefus.valeur.ia.valeur.fournisseurs, machines.valeur.ia.valeur.fournisseurs)
assert.deepEqual(machinesRefus.valeur.ia.valeur.bascules, machines.valeur.ia.valeur.bascules)
assert.deepEqual(trier(machines, () => true, 'salle.machines'), machines)
assert.deepEqual(machines, machinesAvant)
assert.equal(Array.isArray(machinesRefus.valeur.ia.valeur.fournisseurs), true)
